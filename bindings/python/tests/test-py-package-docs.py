"""The documentation of the package (help(opengeode_geosciencesio)) stays
correct: the examples are executed as doctests, every module and bound
function has a docstring and named arguments, and the generated __init__.py of
the wheel carries the same text.

Arguments: the text file of the documentation, the wheel package directory
generated by CMake. This script must not import opengeode_geosciencesio before
the examples: they show the effect of the import."""

import ast
import doctest
import io
import os
import sys

import geode_test_env

import opengeode


def check(condition, message):
    if not condition:
        raise ValueError("[Test] " + message)


def run_examples(documentation):
    parser = doctest.DocTestParser()
    test = parser.get_doctest(documentation, {}, "opengeode_geosciencesio", None, 0)
    check(len(test.examples) >= 5, f"Only {len(test.examples)} examples")
    output = io.StringIO()
    runner = doctest.DocTestRunner(verbose=False, optionflags=doctest.ELLIPSIS)
    runner.run(test, out=output.write)
    results = runner.summarize(verbose=False)
    check(results.failed == 0, f"{results.failed} example(s) failed:\n{output.getvalue()}")


def check_extensions_of_documentation(documentation):
    import opengeode_geosciences

    listed = {
        opengeode.PointSet3D: (["vs", "omf"], ["vs"]),
        opengeode.EdgedCurve3D: (
            ["wl", "dat", "txt", "dev", "pl", "omf", "json"],
            ["pl"],
        ),
        opengeode.TriangulatedSurface3D: (["ts", "omf"], ["ts"]),
        opengeode.PolygonalSurface3D: (["dem", "tif", "tiff", "omf"], []),
        opengeode.HybridSolid3D: (["grdecl"], []),
        opengeode.RegularGrid3D: (["vo"], []),
        opengeode.LightRegularGrid2D: (["tif", "tiff"], []),
        opengeode.LightRegularGrid3D: (["json", "omf"], []),
        opengeode.TetrahedralSolid3D: ([], ["fem"]),
        opengeode_geosciences.StructuralModel: (["ml", "lso"], ["ml", "lso"]),
        opengeode.Section: (["shp", "shz"], []),
        opengeode.BRep: ([], ["ml", "fem"]),
        opengeode_geosciences.HorizonsStack3D: (["xml"], []),
        opengeode_geosciences.HorizonsStack2D: (["xml"], []),
    }
    for cls, (read, written) in listed.items():
        for extension in read:
            check(
                extension in opengeode.input_extensions(cls),
                f"{cls.__name__} should read {extension}",
            )
            check(extension in documentation, f"{extension} is not documented")
        for extension in written:
            check(
                extension in opengeode.output_extensions(cls),
                f"{cls.__name__} should write {extension}",
            )


def check_docstrings(documentation):
    import opengeode_geosciencesio
    import opengeode_geosciencesio_py_mesh
    import opengeode_geosciencesio_py_model
    import mesh_geosciencesio
    import model_geosciencesio

    check(
        opengeode_geosciencesio.__doc__ == documentation,
        "Wrong opengeode_geosciencesio.__doc__",
    )
    for module in [
        mesh_geosciencesio,
        model_geosciencesio,
        opengeode_geosciencesio_py_mesh,
        opengeode_geosciencesio_py_model,
    ]:
        check(
            module.__doc__ and len(module.__doc__) > 40,
            f"No docstring in {module.__name__}",
        )
    for module in [opengeode_geosciencesio_py_mesh, opengeode_geosciencesio_py_model]:
        for name in dir(module):
            member = getattr(module, name)
            if not isinstance(member, type) or member.__module__ != module.__name__:
                continue
            check(member.__doc__, f"No docstring for {name}")
            for method_name, method in vars(member).items():
                if method_name.startswith("_"):
                    continue
                doc = getattr(method, "__doc__", None)
                check(doc, f"No docstring for {name}.{method_name}")
                check("arg0" not in doc, f"Unnamed argument in {name}.{method_name}")


def check_wheel_init(documentation, wheel_directory):
    init = os.path.join(wheel_directory, "__init__.py")
    with open(init, encoding="utf-8") as file:
        content = file.read()
    check(
        ast.get_docstring(ast.parse(content), clean=False) == documentation,
        "Wrong __init__.py docstring",
    )
    for name in ["mesh_geosciencesio", "model_geosciencesio"]:
        path = os.path.join(wheel_directory, name + ".py")
        with open(path, encoding="utf-8") as file:
            module = ast.parse(file.read())
        check(ast.get_docstring(module), f"No docstring in the wheel {name}.py")


if __name__ == "__main__":
    with open(sys.argv[1], encoding="utf-8") as file:
        documentation = file.read()
    run_examples(documentation)
    check_extensions_of_documentation(documentation)
    check_docstrings(documentation)
    check_wheel_init(documentation, sys.argv[2])
